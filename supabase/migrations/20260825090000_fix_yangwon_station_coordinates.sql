-- 양원역(S-I4108-1204) 좌표 오류 정정 — 원본 표준데이터 자체의 오류
--
-- 근거: docs/specs/02-station-master.md §9 "데이터 버그 발견 (2026-08-24)"
--
-- 원인 규명 (2026-08-25): 전국도시철도역사정보표준데이터
-- (data.go.kr/15013205, 2025-04-08 기준, `전체_도시철도역사정보_20260630.xlsx`) 원본 파일을
-- 직접 열어 확인한 결과, 양원역(경의중앙선, 역번호 1204) 행 자체가 역위도/역경도를
-- (36.963729, 129.091321)로 잘못 기재하고 있었다 — 이는 경상북도 포항/영덕 인근 좌표다.
-- 같은 행의 도로명주소 컬럼은 "서울시 중랑구 송림길 147(망우동)"로 정상이라, 위경도 값만
-- 다른 지역 데이터가 잘못 들어간 것으로 보인다. **파싱/적재 배치(scripts/station-master/)의
-- 버그가 아니라 원본 파일 자체의 오기재다** — 컬럼 매핑·CSV 파서·정규화 로직은 이 행의
-- 위경도 문자열을 있는 그대로 정확히 읽어 옮겼을 뿐이다.
--
-- 전수 스캔 결과: station_lines(적재된 944개 물리역, 그룹핑 이후) 및 원본 XLSX 1,099행
-- (그룹핑 이전, region_code 를 못 뽑은 94건 제외 1,005건) 양쪽 모두를 "주소 기반 region_code
-- vs 좌표가 가리키는 지역" 대략적 경계 박스로 전수 대조했다. 이 역 1건만 나왔다 — 원본 파일에
-- 같은 유형의 오류가 더 있는지도 함께 확인했으나 추가 발견 없음. (서생역도 처음엔 걸렸지만
-- 인접역과의 위경도 연속성이 자연스러워 울산/부산 행정경계에 걸친 대략적 경계 박스의
-- 오탐으로 판정, 정정 대상 아님.)
--
-- 조치:
--  1) 이 마이그레이션으로 이미 적재된 DB 값을 즉시 정정한다. 배치 재실행을 기다리지 않는다 —
--     이 좌표가 카카오맵 지도 보기(07-map-view.md) 핀 위치에 그대로 쓰이고 있어, 지금 이
--     역을 방문 기록한 커플의 화면에는 핀이 경북 포항 부근에 찍히는 상태였다.
--  2) 재적재(`npm run stations:load`)해도 같은 오류가 원본 파일에서 되살아나지 않도록
--     scripts/station-master/known-corrections.mjs 에 같은 정정값을 "알려진 원천 오류"로
--     등록했다 — load-station-master.mjs 가 fetch 직후(정규화 이전) 자동 적용한다.
--     이 마이그레이션은 "지금 당장"을, known-corrections.mjs 는 "다음 재적재부터"를
--     담당한다. 둘 다 고쳐야 재발이 완전히 막힌다(전자만 하면 재적재 시 되돌아가고,
--     후자만 하면 다음 배치 전까지 여전히 틀린 채로 서비스된다).
--
-- 정정 좌표 출처: OpenStreetMap Nominatim 실측(2026-08-25, "양원역" railway=station 노드,
-- 서울 중랑구 망우동, 37.6065818/127.1079346 — 인근 bus_stop 노드 37.6062102/127.1074875도
-- 같은 위치를 가리켜 상호 검증됨). 인접역(경의중앙선 seq 6 망우역 37.599288,127.092318 /
-- seq 8 구리역 37.60326,127.143373) 사이 경로 상에 자연스럽게 들어맞는 것도 함께 확인했다.
-- 소수점 6자리로 반올림해 이 데이터셋의 다른 좌표들과 정밀도를 맞췄다.
-- ============================================================================

do $$
declare
  v_updated int;
begin
  update public.stations
     set lat = 37.606582,
         lng = 127.107935
   where code = 'S-I4108-1204'
     and (lat, lng) is distinct from (37.606582, 127.107935);
  get diagnostics v_updated = row_count;

  -- 로컬 검증(PGlite, supabase/tests)에는 실 데이터가 없어 이 역이 존재하지 않는다.
  -- 그 경우 v_updated = 0 이라 아래 블록이 전부 스킵된다 — 의도된 동작이다(테스트 DB에
  -- 없는 행을 손대거나 master_version 을 엉뚱하게 올리면 안 된다).
  if v_updated > 0 then
    -- station_lines 는 그룹 평균 이전의 노선별 원천 좌표다(F-07 재계산 입력값이므로
    -- stations.lat/lng 와 별개로 여기도 맞춰야 다음 그룹 평균 계산이 다시 틀어지지 않는다).
    update public.station_lines sl
       set lat = 37.606582,
           lng = 127.107935
      from public.stations st, public.lines l
     where sl.station_id = st.id
       and sl.line_id = l.id
       and st.code = 'S-I4108-1204'
       and l.code = 'L-I4108';

    -- F-09: 이미 잘못된 좌표를 캐시한 클라이언트가 있을 수 있으므로 master_version 을 올려
    -- 다음 접속 때 마스터를 재다운로드하게 만든다.
    update public.app_settings
       set value = jsonb_build_object(
             'version', coalesce((value ->> 'version')::int, 0) + 1,
             'applied_at', now()
           )
     where key = 'master_version';
  end if;
end $$;
